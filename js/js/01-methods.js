// Strings
const myVariable = "Mathematics";

// String methods
console.log(myVariable.charAt(0));

// indexOf show first position of charactor
console.log(myVariable.indexOf("mat"));

// lastIndexOf show last position of charactor
console.log(myVariable.lastIndexOf("at"));

// slice used for slice front of charactor.
console.log(myVariable.slice(5));

// UpperCase and LowerCase
console.log(myVariable.toLowerCase());
console.log(myVariable.toUpperCase());

// split it mean not include if it's split it.
console.log(myVariable.split("e"));